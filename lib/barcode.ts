/**
 * Barcode utilities for EAN-13 and electronic retail scales (CAS, Rongta, Digi, Toledo, Bizerba)
 * Supports weight-embedded (20, 21) and price-embedded (22, 23) barcodes.
 */

/**
 * Calculates EAN-13 Check Digit using standard Modulo 10 algorithm.
 * @param twelveDigits 12-digit numeric string
 * @returns Check digit between 0 and 9
 */
export function calculateEan13CheckDigit(twelveDigits: string): number {
  if (twelveDigits.length !== 12 || !/^\d+$/.test(twelveDigits)) {
    throw new Error("Input must be exactly 12 numeric digits");
  }

  let sum = 0;
  for (let i = 0; i < 12; i++) {
    const digit = parseInt(twelveDigits[i], 10);
    // 0-indexed: index 0, 2, 4, 6, 8, 10 are odd positions in 1-based indexing (weight = 1)
    // index 1, 3, 5, 7, 9, 11 are even positions in 1-based indexing (weight = 3)
    sum += i % 2 === 0 ? digit * 1 : digit * 3;
  }

  const remainder = sum % 10;
  return remainder === 0 ? 0 : 10 - remainder;
}

/**
 * Validates a 13-digit EAN-13 barcode against its check digit.
 */
export function validateEan13(barcode: string): boolean {
  if (!barcode || barcode.length !== 13 || !/^\d+$/.test(barcode)) return false;
  const body = barcode.slice(0, 12);
  const expectedCheck = calculateEan13CheckDigit(body);
  return parseInt(barcode[12], 10) === expectedCheck;
}

/**
 * Generates an EAN-13 scale barcode for a weighted product.
 * Format: [PP (2 digits)] [IIIII (5 digits PLU)] [WWWWW (5 digits grams)] [C (1 check digit)]
 */
export function generateScaleBarcode(
  prefix: string = "20",
  plu: string | number,
  weightKg: number
): string {
  const pFix = prefix.padStart(2, "0").slice(0, 2);
  const cleanPlu = String(plu).replace(/\D/g, "").padStart(5, "0").slice(-5);
  const weightGrams = Math.round(weightKg * 1000);
  const cleanWeight = String(weightGrams).padStart(5, "0").slice(-5);

  const twelve = `${pFix}${cleanPlu}${cleanWeight}`;
  const checkDigit = calculateEan13CheckDigit(twelve);
  return `${twelve}${checkDigit}`;
}

export interface ScaleBarcodeResult {
  isScaleBarcode: boolean;
  mode?: "weight" | "price";
  prefix?: string;
  plu?: string;
  weightKg?: number;
  embeddedPrice?: number;
  raw: string;
}

export interface ScaleConfig {
  weightPrefixes?: string; // e.g. "20,21"
  pricePrefixes?: string;  // e.g. "22,23"
  pluDigits?: number;      // e.g. 5
}

/**
 * Parses any barcode scanned at the Cashier POS to detect if it's an EAN-13 barcode
 * generated by a digital scale sticker.
 */
export function parseScaleBarcode(
  barcode: string,
  config?: ScaleConfig
): ScaleBarcodeResult {
  const clean = barcode.trim();
  if (clean.length !== 13 || !/^\d+$/.test(clean)) {
    return { isScaleBarcode: false, raw: clean };
  }

  const weightPrefixList = (config?.weightPrefixes || "20,21")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);

  const pricePrefixList = (config?.pricePrefixes || "22,23")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);

  const pluLength = config?.pluDigits || 5;
  const prefix = clean.slice(0, 2);

  // Check weight-embedded barcode (e.g. 20 00002 00240 6)
  if (weightPrefixList.includes(prefix)) {
    const pluPart = clean.slice(2, 2 + pluLength);
    const weightPart = clean.slice(2 + pluLength, 12);
    const grams = parseInt(weightPart, 10);
    const weightKg = Number((grams / 1000).toFixed(3));

    return {
      isScaleBarcode: true,
      mode: "weight",
      prefix,
      plu: pluPart,
      weightKg,
      raw: clean,
    };
  }

  // Check price-embedded barcode (e.g. 22 00002 00432 0)
  if (pricePrefixList.includes(prefix)) {
    const pluPart = clean.slice(2, 2 + pluLength);
    const pricePart = clean.slice(2 + pluLength, 12);
    const piasters = parseInt(pricePart, 10);
    const embeddedPrice = Number((piasters / 100).toFixed(2));

    return {
      isScaleBarcode: true,
      mode: "price",
      prefix,
      plu: pluPart,
      embeddedPrice,
      raw: clean,
    };
  }

  return { isScaleBarcode: false, raw: clean };
}
